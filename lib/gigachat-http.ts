type GigaChatRequestOptions = {
  method: "GET" | "POST";
  headers?: Record<string, string>;
  body?: string;
  timeoutMs?: number;
};

export type GigaChatHttpResponse<T> = {
  ok: boolean;
  status: number;
  data: T;
};

export function requestGigaChatJson<T>(url: string, options: GigaChatRequestOptions): Promise<GigaChatHttpResponse<T>> {
  return new Promise((resolve, reject) => {
    const body = options.body ?? "";
    const req = request(url, {
      method: options.method,
      ca: RUSSIAN_TRUSTED_ROOT_CA,
      headers: {
        ...options.headers,
        ...(body ? { "Content-Length": String(Buffer.byteLength(body)) } : {}),
      },
    }, (response) => {
      const chunks: Buffer[] = [];
      let size = 0;

      response.on("data", (chunk: Buffer) => {
        size += chunk.length;
        if (size > 1_000_000) {
          req.destroy(new Error("GigaChat response exceeded the safety limit"));
          return;
        }
        chunks.push(chunk);
      });
      response.on("end", () => {
        try {
          const text = Buffer.concat(chunks).toString("utf8");
          const data = (text ? JSON.parse(text) : {}) as T;
          const status = response.statusCode ?? 500;
          resolve({ ok: status >= 200 && status < 300, status, data });
        } catch {
          reject(new Error("GigaChat returned an invalid JSON response"));
        }
      });
    });

    req.setTimeout(options.timeoutMs ?? 20_000, () => {
      req.destroy(new Error("GigaChat request timed out after 20 seconds"));
    });
    req.on("error", reject);
    if (body) req.write(body);
    req.end();
  });
}
